import WhyPanel from './WhyPanel.tsx';

/** 各ステージの下に置く「なぜ？」パネルの文面 */
export const WhyStage1 = () => (
  <WhyPanel title="2枚反転すると見逃すのはなぜ？">
    <p>1枚が反転すると、1の数は1つ増えるか1つ減るので、偶数と奇数が入れ替わります。だから必ず気づけます。</p>
    <p>2枚が反転すると、1の数は2つ変わるか、増えた分と減った分で変わりません。偶数と奇数が元に戻ってしまうので、気づけないのです。</p>
  </WhyPanel>
);

export const WhyStage2 = () => (
  <WhyPanel title="偶数パリティと奇数パリティのちがい">
    <p>パリティビットは、「1の数をそろえるために足す、最後の1枚」です。</p>
    <ul>
      <li>偶数パリティ：全部合わせた1の数が偶数になるように、最後に0か1を足します。</li>
      <li>奇数パリティ：全部合わせた1の数が奇数になるように、最後に0か1を足します。</li>
    </ul>
    <p>受け取った側は1の数を数えて、約束どおり（偶数か奇数か）になっていなければ「どこかが変わった！」と気づけます。</p>
    <p><strong>どうして2種類あるの？</strong></p>
    <p>もし、ケーブルが抜けたり機械が止まったりして、0しか届かなくなったら……？</p>
    <ul>
      <li>偶数パリティだと、全部0は「1が0個＝偶数」なので、正しいと判定されてしまいます。</li>
      <li>奇数パリティだと、正しいデータには必ず1が1つ以上あるので、全部0が届いたら「おかしい！」とすぐに気づけます。</li>
    </ul>
  </WhyPanel>
);

export const WhyStage3 = () => (
  <WhyPanel title="どうして場所まで分かるの？">
    <p>1列に並べたパリティでは、「どこかがおかしい」ことしか分かりません。</p>
    <p>縦と横の両方にパリティを付けると、おかしい行とおかしい列が1本ずつ見つかります。その交点が、反転したカードです。</p>
    <p>0と1しかないので、場所が分かればめくり直すだけで元に戻せます。</p>
    <p>ただし、2枚以上が反転すると、交点の候補がいくつもできて場所を決められないことがあります。</p>
  </WhyPanel>
);
